@router.get("/transactions", response_class=HTMLResponse)
async def transactions(request: Request, download: Optional[str] = None):
    from main import orchestrator
    session = get_session(request)
    redirect = _require_login(request, session)
    if redirect:
        return redirect

    notice = ""
    if download:
        session["download_count"] += 1
        orchestrator.sim.events.append(_mk_event(session, "download", "demo:transactions/export", "success", egress=1200))
        if session["download_count"] >= DOWNLOAD_THRESHOLD:
            events = [_mk_event(session, "download", f"demo:transactions/DEMO-{i:03d}", "success", egress=900)
                      for i in range(session["download_count"])]
