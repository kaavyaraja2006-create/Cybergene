INJECTION_PATTERNS = re.compile(r"(\bOR\b\s+1=1|UNION\s+SELECT|--|;\s*DROP\b|'\s*OR\s*')", re.IGNORECASE)
XSS_PATTERNS = re.compile(r"(<script|onerror\s*=|onload\s*=|javascript:)", re.IGNORECASE)
TRAVERSAL_PATTERNS = re.compile(r"(\.\./|\.\.\\|^/|^[A-Za-z]:\\)")

SESSION_COOKIE = "cybergene_demo_session"

# In-memory session store -- fine for a local demo; resets on restart.
SESSIONS: dict = {}

FAIL_THRESHOLD = 5           # failed logins before CYBERGENE engages
STRIKE_THRESHOLD = 2         # suspicious search/comment/file attempts before CYBERGENE engages
DOWNLOAD_THRESHOLD = 6       # transaction downloads before flagged as exfiltration
RATE_WINDOW_SECONDS = 10
RATE_THRESHOLD = 12          # requests within the window before flagged as API abuse


def _new_session() -> dict:
    return {
        "user": None, "role": "guest", "name": None,
        "failed_logins": 0, "attempted_usernames": set(),
        "search_strikes": 0, "comment_strikes": 0, "file_strikes": 0,
        "download_count": 0, "request_times": [],
        "blocked_until": 0.0, "blocked_reason": None,
        "session_id": uuid.uuid4().hex[:8],
        "created": time.time(),
    }


def get_session(request: Request) -> dict:
    sid = request.cookies.get(SESSION_COOKIE)
    if not sid or sid not in SESSIONS:
        s = _new_session()
        SESSIONS[s["session_id"]] = s
        request.state._new_sid = s["session_id"]
        return s
    return SESSIONS[sid]


def _touch_rate(session: dict) -> bool:
    """Track a sliding request window; returns True if API-abuse threshold crossed."""
    now = time.time()
    session["request_times"] = [t for t in session["request_times"] if now - t < RATE_WINDOW_SECONDS]
    session["request_times"].append(now)
    return len(session["request_times"]) >= RATE_THRESHOLD


def _mk_event(session, action, resource, status, cpu=25, mem=25, egress=60) -> Event:
    return Event(
        event_id=uuid.uuid4().hex[:12], ts=time.time(),
        user=session["user"] or "anon", service="demo-web", action=action,
        resource=resource, status=status, cpu_pct=cpu, memory_pct=mem,
        network_egress_kbps=egress, src_port=443, label="attack",
        attack_type=None, session_id=session["session_id"],
    )


def _is_blocked(session) -> Optional[str]:
    if session["blocked_until"] and time.time() < session["blocked_until"]:
        remaining = round(session["blocked_until"] - time.time())
        return f"CYBERGENE has restricted this session ({session.get('blocked_reason', 'policy')}). Try again in ~{remaining}s."
    return None


def _apply_defense(session: dict, action: str) -> str:
    """Translate an allowlisted CYBERGENE response action into a visible,
    reversible consequence for this demo session."""
    if action in ("rate_limit", "block_ip"):
        session["blocked_until"] = time.time() + 30
        session["blocked_reason"] = action
        return f"CYBERGENE applied '{action}' — this session is rate-limited for 30 seconds."
    if action == "rotate_credentials":
        session["blocked_until"] = time.time() + 20
        session["blocked_reason"] = "rotate_credentials"
        return "CYBERGENE forced a credential reset — login is temporarily disabled for this session."
    if action in ("isolate_pod", "disable_function"):
        session["user"] = None
        session["role"] = "guest"
        return f"CYBERGENE applied '{action}' — this session has been logged out and isolated."
    return f"CYBERGENE applied '{action}'."


