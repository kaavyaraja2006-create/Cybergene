@router.post("/login")
async def login_submit(request: Request, username: str = Form(...), password: str = Form(...)):
    from main import orchestrator  # local import to avoid a circular import at module load
    session = get_session(request)

    blocked = _is_blocked(session)
    if blocked:
        resp = HTMLResponse(layout("Log in", f'<div class="card"><div class="alert">{blocked}</div></div>', session))
        _set_cookie_if_new(request, resp)
        return resp

    account = DEMO_USERS.get(username)
    ok = account is not None and account["password"] == password

    if ok:
        session["user"] = username
        session["role"] = account["role"]
        session["name"] = account["name"]
        session["failed_logins"] = 0
        session["attempted_usernames"] = set()
        resp = RedirectResponse("/demo/dashboard", status_code=303)
        _set_cookie_if_new(request, resp)
        return resp

    # failed login -- buffer telemetry and check thresholds
    session["failed_logins"] += 1
    session["attempted_usernames"].add(username)
    events = [_mk_event(session, "login", "auth:login", "failed", cpu=18, mem=22, egress=45)
              for _ in range(1)]

    notice = ""
    if session["failed_logins"] >= FAIL_THRESHOLD:
        stuffing = len(session["attempted_usernames"]) >= 3
        label = "Credential Stuffing" if stuffing else "Login Abuse / Brute Force"
        category = "credential_abuse"
        all_events = [
            _mk_event(session, "login", "auth:login", "failed", cpu=18, mem=22, egress=45)
            for _ in range(session["failed_logins"])
        ]
        result = orchestrator.ingest_live_event_burst(
            all_events, category,
            header=f"Live demo bank: {label} detected — {session['failed_logins']} failed logins "
                    f"across {len(session['attempted_usernames'])} username(s)."
        )
        action = result["incident"]["recommended_action"]
        contained = result["incident"].get("outcome_success", False)
        consequence = _apply_defense(session, action)
        session["failed_logins"] = 0
        session["attempted_usernames"] = set()
        notice = (
            f'<div class="alert"><b>🚨 CYBERGENE detected {label}</b><br>'
            f'DNA: {result["dna"]["dna_id"]} · Recommended response: <b>{action}</b> · '
            f'Outcome: {"contained" if contained else "response failed, DNA evolving"}<br>{consequence}</div>'
        )
    else:
        orchestrator.sim.events.extend(events)  # still visible on the Live Telemetry page

    body = f"""
    <div class="card">
      {notice or '<div class="alert">Invalid username or password.</div>'}
      <h2>Log in</h2>
      <form method="post" action="/demo/login">
        <label>Username</label><input name="username" required>
        <label>Password</label><input type="password" name="password" required>
        <button class="btn" type="submit">Log in</button>
      </form>
    </div>"""
    resp = HTMLResponse(layout("Log in", body, session))
    _set_cookie_if_new(request, resp)
    return resp


