def _set_cookie_if_new(request: Request, response):
    sid = getattr(request.state, "_new_sid", None)
    if sid:
        response.set_cookie(SESSION_COOKIE, sid, httponly=True)


def _require_login(request: Request, session: dict):
    if not session["user"]:
        return RedirectResponse("/demo/login", status_code=303)
